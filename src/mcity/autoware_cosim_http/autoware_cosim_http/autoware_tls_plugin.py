class AutowareTLSPlugin(Node):

    def __init__(self, **kwargs):
        super().__init__("autoware_tls_plugin", **kwargs)

        # Declare parameters
        self.declare_parameter("http_host", "localhost")
        self.declare_parameter("http_port", 8000)
        self.declare_parameter("simulation_id", "")

        self.http_host = self.get_parameter("http_host").value
        self.http_port = self.get_parameter("http_port").value
        self.simulation_id = self.get_parameter("simulation_id").value

        self.base_url = f"http://{self.http_host}:{self.http_port}"
        self.session = requests.Session()

        # Publisher
        self.pub_traffic_signals = self.create_publisher(
            TrafficSignalArray,
            "/perception/traffic_light_recognition/traffic_signals",
            10,
        )

        # Event-driven: subscribe to tick_complete instead of polling on timer
        self.sub_tick = self.create_subscription(
            Float64, '/terasim/tick_complete', self.on_tick, 10
        )

        # Re-publish cached signals periodically so Autoware never sees stale data
        self.republish_timer = self.create_timer(0.1, self.republish)
        self._last_msg = None

        # State cache
        self.last_state = None
        self._stopline_tl_ids = set()
        self._crosswalk_tl_ids = set()
        self._coverage_logged = False
        self._sim_time = 0.0

        self.get_logger().info(f"TLS plugin started: {self.base_url}, sim_id={self.simulation_id}")

        # Unmapped-regelem fallback:
        # Autoware lanelet2 map may declare traffic_light regulatory_elements for
        # junctions that SUMO net.xml treats as `priority` (no TLS). For those
        # regelems no SUMO state can be looked up — `traffic_light_module` then
        # logs "traffic signal data ... not received" and blocks the planner,
        # eventually leading to MRM_SUCCEEDED latch. As a fallback we publish
        # GREEN for every traffic_light regelem in the map that is NOT covered by
        # SUMO_TO_AUTOWARE_TLS_MAPPING. This lets Autoware proceed past those
        # phantom-TLS junctions while keeping real mapped TLSes accurate.
        self.declare_parameter(
            "lanelet2_map_path",
            "/home/haotian/Projects/Isuzu_cosim/autoware/map/AA_Fixed_V14/AA_Fixed_V14_lanelet2.osm",
        )
        self.lanelet2_map_path = self.get_parameter("lanelet2_map_path").value

        mapped_reg_ids = {rid for entries in SUMO_TO_AUTOWARE_TLS_MAPPING.values() for rid, _ in entries}
        self._unmapped_reg_ids = self._scan_unmapped_tl_reg_ids(mapped_reg_ids)
        # Report coverage for THIS map only. The raw dict spans every scenario
        # (Ann Arbor + Hiratsuka), so its size says nothing about how much of the
        # loaded map is actually driven by SUMO — quoting it hid a 39% coverage
        # behind a "398 reg_ids mapped" line.
        in_map = self._scan_tl_reg_ids()
        covered = in_map & mapped_reg_ids if in_map else set()
        pct = (100.0 * len(covered) / len(in_map)) if in_map else 0.0
        self.get_logger().info(
            f"TLS mapping for {os.path.basename(self.lanelet2_map_path)}: "
            f"{len(covered)}/{len(in_map)} traffic_light regelems follow SUMO ({pct:.0f}%); "
            f"{len(self._unmapped_reg_ids)} unmapped-with-stopline published as GREEN "
            f"(SUMO has no TLS there, so its own traffic is uncontrolled too)."
        )
        if self._unmapped_reg_ids:
            self.get_logger().warn(
                "GREEN-fallback reg_ids (NOT following SUMO): "
                + ",".join(str(r) for r in sorted(self._unmapped_reg_ids))
            )

    def _scan_tl_reg_ids(self):
        """All traffic_light regulatory-element ids present in the loaded map.

        Used only to report the real coverage of this map (mapped vs GREEN-fallback).
        """
        if not os.path.isfile(self.lanelet2_map_path):
            return set()
        try:
            root = ET.parse(self.lanelet2_map_path).getroot()
        except Exception:
            return set()
        ids = set()
        for rel in root.findall("relation"):
            tags = {t.get("k"): t.get("v") for t in rel.findall("tag")}
            if tags.get("type") == "regulatory_element" and tags.get("subtype") == "traffic_light":
                try:
                    ids.add(int(rel.get("id")))
                except (TypeError, ValueError):
                    pass
        return ids

    def _scan_unmapped_tl_reg_ids(self, mapped_reg_ids):
        """Parse lanelet2 .osm, return regulatory_element ids of type=traffic_light
        that are NOT in mapped_reg_ids. Publishing GREEN for these unblocks the
        Autoware planner when Autoware map has a TLS that SUMO does not."""
        if not os.path.isfile(self.lanelet2_map_path):
            self.get_logger().warn(f"lanelet2 map not found, no unmapped fallback: {self.lanelet2_map_path}")
            return set()
        try:
            root = ET.parse(self.lanelet2_map_path).getroot()
        except Exception as exc:
            self.get_logger().error(f"failed to parse lanelet2 map: {exc}")
            return set()
        # Only publish GREEN for regelems that ALSO have a ref_line (stop line) member.
        # Phantom regelems with traffic_light tag but no ref_line cause behavior_velocity_planner
        # to log [FATAL] "No stop line at traffic_light_reg_elem_id = ..., please fix the map!"
        # which crashes the planner container.
        all_tl = set()
        for r in root.iter("relation"):
            tags = {t.attrib.get("k"): t.attrib.get("v") for t in r.findall("tag")}
            if tags.get("type") != "regulatory_element" or tags.get("subtype") != "traffic_light":
                continue
            has_ref_line = any(m.attrib.get("role") == "ref_line" for m in r.findall("member"))
            if not has_ref_line:
                continue  # skip — would FATAL Autoware
            try:
                all_tl.add(int(r.attrib["id"]))
            except (KeyError, ValueError):
                continue
        self._stopline_tl_ids = all_tl
        # pedestrian lights: traffic_light regelems referred to by crosswalk lanelets
        tl_any = set()
        for r in root.iter("relation"):
            tags = {t.attrib.get("k"): t.attrib.get("v") for t in r.findall("tag")}
            if tags.get("type") == "regulatory_element" and tags.get("subtype") == "traffic_light":
                tl_any.add(r.attrib.get("id"))
        for r in root.iter("relation"):
            tags = {t.attrib.get("k"): t.attrib.get("v") for t in r.findall("tag")}
            if tags.get("type") == "lanelet" and tags.get("subtype") == "crosswalk":
                self._crosswalk_tl_ids |= {int(m.attrib["ref"]) for m in r.findall("member")
                                           if m.attrib.get("role") == "regulatory_element"
                                           and m.attrib.get("ref") in tl_any}
        return all_tl - mapped_reg_ids

    def _add_unmapped_green(self, signals):
        """Populate `signals` dict with GREEN TrafficSignal for every unmapped reg_id
        that wasn't already filled by the SUMO-driven mapping above."""
        for reg_id in self._unmapped_reg_ids:
            if reg_id in signals:
                continue
            elem = TrafficSignalElement()
            elem.shape = TrafficSignalElement.CIRCLE
            elem.status = TrafficSignalElement.SOLID_ON
            elem.confidence = 1.0
            elem.color = TrafficSignalElement.GREEN
            sig = TrafficSignal()
            sig.traffic_signal_id = reg_id
            sig.elements = [elem]
            signals[reg_id] = sig

    def _get_state(self):
        """Get simulation state from TeraSim HTTP API."""
        if not self.simulation_id:
            return None
        try:
            resp = self.session.get(
                f"{self.base_url}/simulation/{self.simulation_id}/state",
                timeout=0.5
            )
            self.last_state = resp.json()
            self._sim_time = self.last_state.get("simulation_time", 0.0)
            return self.last_state
        except:
            return self.last_state

    def on_tick(self, tick_msg):
        """Called once per SUMO step — publish traffic light states to Autoware."""
        self._sim_time = tick_msg.data

        state = self._get_state()
        signals = {}
        if not state or "traffic_light_details" not in state:
            # Still publish the unmapped-GREEN baseline so phantom-TLS lanelets
            # don't block the planner during state-fetch hiccups.
            self._add_unmapped_green(signals)
            msg = TrafficSignalArray()
            msg.stamp = self.get_clock().now().to_msg()
            msg.signals = list(signals.values())
            self.pub_traffic_signals.publish(msg)
            self._last_msg = msg
            return


        # Each reg_elem maps to exactly 1 SUMO link (straight-priority dedup).
        # No aggregation needed. Priority kept for safety if duplicates exist.
        COLOR_PRIORITY = {
            TrafficSignalElement.GREEN: 0,
            TrafficSignalElement.AMBER: 1,
            TrafficSignalElement.RED: 2,
        }
        color_map = {
            'r': TrafficSignalElement.RED,
            'y': TrafficSignalElement.AMBER,
            'g': TrafficSignalElement.GREEN,  # 2026-07-30 Hiratsuka: permissive green -> GREEN (JP nets are mostly permissive; AA-era protected-only rule starves minor approaches)
            'G': TrafficSignalElement.GREEN,  # protected green -> GREEN
        }

        if not self._coverage_logged:
            self._log_live_coverage(state["traffic_light_details"].keys())

        # Process each SUMO traffic light
        for tls_id, tls_info in state["traffic_light_details"].items():
            state_str = tls_info.get("tls", "") if isinstance(tls_info, dict) else tls_info

            # Map to Autoware regulatory elements
            # A reg_elem may have multiple link indices (e.g. shared between straight/turn).
            # Use LEAST RESTRICTIVE: if ANY link is GREEN, signal is GREEN.
            for reg_id, lane_idx in SUMO_TO_AUTOWARE_TLS_MAPPING.get(tls_id, []):
                light = state_str[lane_idx] if lane_idx < len(state_str) else 'r'
                color = color_map.get(light, TrafficSignalElement.RED)

                if reg_id in signals:
                    # Keep the least restrictive color (lowest priority = more permissive)
                    existing = signals[reg_id].elements[0].color
                    if COLOR_PRIORITY.get(color, 0) < COLOR_PRIORITY.get(existing, 0):
                        signals[reg_id].elements[0].color = color
                else:
                    elem = TrafficSignalElement()
                    elem.shape = TrafficSignalElement.CIRCLE
                    elem.status = TrafficSignalElement.SOLID_ON
                    elem.confidence = 1.0
                    elem.color = color

                    sig = TrafficSignal()
                    sig.traffic_signal_id = reg_id
                    sig.elements = [elem]
                    signals[reg_id] = sig

        # Overlay GREEN for every unmapped traffic_light regelem so phantom-TLS
        # lanelets (Autoware-side TLS with no SUMO counterpart) don't block planner.
        self._add_unmapped_green(signals)

        # Use the node's clock (sim time if use_sim_time=true, wall clock otherwise)
        # This ensures the stamp always matches what Autoware expects
        msg = TrafficSignalArray()
        msg.stamp = self.get_clock().now().to_msg()
        msg.signals = list(signals.values())
        self.pub_traffic_signals.publish(msg)
        self._last_msg = msg  # cache for re-publish

    def _log_live_coverage(self, live_tls_ids):
        """Once per run: coverage against the TLS ids this scenario really has.

        The startup line counts a regelem as mapped if ANY scenario's table
        names it; this one only counts bindings to TLS present in the sim."""
        self._coverage_logged = True
        live = {rid for tid in live_tls_ids for rid, _ in SUMO_TO_AUTOWARE_TLS_MAPPING.get(tid, [])}
        stop = self._stopline_tl_ids
        silent = stop - live - self._unmapped_reg_ids
        self.get_logger().info(
            f"live TLS coverage: {len(stop & live)}/{len(stop)} stop-line traffic lights follow "
            f"SUMO ({len(list(live_tls_ids))} TLS in this scenario); "
            f"{len(self._unmapped_reg_ids & stop)} GREEN fallback; {len(silent)} not published"
            + (f" ({','.join(str(r) for r in sorted(silent))})" if silent else "")
            + (f"; crosswalk lights: {len(self._crosswalk_tl_ids & live)}/{len(self._crosswalk_tl_ids)} follow SUMO"
               if self._crosswalk_tl_ids else ""))

    def republish(self):
        """Re-publish cached TLS signals with fresh timestamp to prevent staleness."""
        if self._last_msg is not None:
            self._last_msg.stamp = self.get_clock().now().to_msg()
            self.pub_traffic_signals.publish(self._last_msg)


def main(args=None):
    rclpy.init(args=args)
    node = AutowareTLSPlugin()
    rclpy.spin(node)
    node.destroy_node()
    rclpy.shutdown()


if __name__ == "__main__":
    main()
